<h2>2. À 12 mois avant : Construire la structure</h2>

<p>C'est le gros travail. À ce point tu dois avoir booked tes trois piliers : <strong>lieu, traiteur, photographe.</strong> C'est 70% de ton budget, donc ça d'abord.</p>

<h3>Essentiels (vraiment fais-les)</h3>

<p><strong>Cherche et visite des lieux</strong></p>
<ul>
<li>Fais une liste de 5-7 lieux potentiels dans ta région / ta préférence</li>
<li>Visite-les vraiment (pas en photos)</li>
<li>Prends des notes sur chacun : prix, capacité, quoi qu'il inclut, vibe générale</li>
<li>Demande les disponibilités pour ta date préférée</li>
</ul>
<p>Deadline : avoir booké le lieu d'ici la fin du mois.</p>

<p><strong>Cherche des traiteurs et teste leurs menus</strong></p>
<ul>
<li>Fait une liste de 3-4 traiteurs dans ta région</li>
<li>Demande une dégustation — c'est gratuit ou -30€ généralement</li>
<li>Goûte vraiment. C'est 30% de ce qu'on se souvient du mariage.</li>
<li>Récupère les tarifs (par personne, ce qu'est inclus, options)</li>
</ul>
<p>Deadline : avoir choisi et signé avec le traiteur d'ici 2-3 mois.</p>

<p><strong>Cherche un photographe</strong></p>
<ul>
<li>Regarde les portfolios de 5-6 photographes</li>
<li>Fixe-toi un budget (1500€ ? 2500€ ?)</li>
<li>Contacte les trois que tu aimes</li>
<li>Rencontre-les si tu peux (au moins par vidéo)</li>
</ul>
<p>Deadline : book d'ici 2 mois. Les bons photographes se remplissent vite.</p>

<p><strong>Discute musique et ambiance</strong></p>
<ul>
<li>DJ ou playlist ? Groupe live ?</li>
<li>Demande des devis si tu veux un prestataire</li>
</ul>
<p>Deadline : décider avant 6 mois.</p>

<p><strong>Parle des plans pratiques avec ton futur mari</strong></p>
<ul>
<li>Combien de demoiselles/garçons d'honneur vraiment ?</li>
<li>Qui paie quoi dans la famille ? (Robe de mariée, costume, etc.)</li>
<li>Qui gère la logistique ?</li>
<li>Comment on accueille les invités (parking, hébergement, prise en charge ?)</li>
</ul>

<h3>Choses utiles (mais pas obligatoires)</h3>
<ul>
<li>Créer un document partagé avec le partner avec les éléments clés (budget, contacts, deadlines)</li>
<li>Créer un tableau sur Pinterest "l'ambiance du mariage"</li>
<li>Commencer à suivre des fleuristes et décorateurs locaux</li>
