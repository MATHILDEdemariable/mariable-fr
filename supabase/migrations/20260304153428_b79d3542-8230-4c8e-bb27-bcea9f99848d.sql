<h2>FAQ</h2>

<p><strong>Et si je booste pas les prestataires à 12 mois ?</strong></p>
<p>Les bons photographes et les bons lieux se remplissent 12-18 mois avant. Tu vas être stressée et peut-être pas avoir ton premier choix. Sérieusement, book les prestataires clés à 12 mois.</p>

<p><strong>Je peux faire une checklist plus courte ?</strong></p>
<p>Honnêtement ? À peu près. Il y a trois choses que tu dois absolument faire : décider, booker les prestataires, envoyer les faire-parts. Tout le reste est construction dessus.</p>

<p><strong>Comment j'utilise cette checklist si j'ai moins de 12 mois pour m'organiser ?</strong></p>
<p>Compresse les timelines. Tu as 6 mois ? Fais les "12 mois" tasks le mois prochain. Tu as 3 mois ? Tu fais les "18 mois" tasks maintenant, les "12 mois" tasks dans 2 semaines. Ça reste faisable, juste c'est plus tight.</p>

<p><strong>Est-ce que je dois vraiment acheter la robe à 6 mois ?</strong></p>
<p>Sérieusement oui. Les ajustements c'est 4-8 semaines. Si tu l'achètes à 3 mois et qu'il y a un problème (mauvaise taille, faut la commander ailleurs), tu peux être en galère. 6 mois c'est safe.</p>

<p><strong>Et si je change d'avis sur quelque chose à 1 mois avant ?</strong></p>
<p>Pense deux fois. La plupart des changements à 1 mois avant c'est de l'anxiété qui parle, pas une vraie raison. Vraiment tu veux changer le menu ? Honnêtement ok. Tu veux redécorer le lieu en entier ? Non.</p>

<p><strong>Comment je gère les changements d'invités à la dernière minute ?</strong></p>
<p>Quelqu'un annule 2 semaines avant ? C'est pas un problème, tu le dis au traiteur. Quelqu'un ajoute deux invités à la dernière minute ? Tu dis non. Le traiteur a besoin de savoir le nombre, le lieu a une capacité, ça bouge pas à 2 semaines avant.</p>

