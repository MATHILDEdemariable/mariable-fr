<h2>3. À 6 mois avant : Affiner et confirmer</h2>

<p>À ce stade, les gros trucs sont lockés. Tu dois refiner les détails sans créer de chaos.</p>

<h3>Essentiels (vraiment fais-les)</h3>

<p><strong>Envoie les faire-parts</strong></p>
<ul>
<li>Design : 3-4 semaines avant l'envoi</li>
<li>Impression : 2-3 semaines</li>
<li>Envoi : maintenant, pour que les gens répondent d'ici 2-3 mois</li>
<li>Délai de réponse sur le faire-part : 3 semaines avant le mariage</li>
<li>Tu reçois les réponses d'ici fin juillet pour un mariage en septembre</li>
</ul>

<p><strong>Confirme avec tous les prestataires</strong></p>
<ul>
<li>Lieu : confirme les accès, parking, timing, équipements disponibles</li>
<li>Traiteur : confirme le nombre d'invités (c'est une estimation pour l'instant), le menu exact (c'est maintenant)</li>
<li>Photographe : les horaires, le timing du jour J, où tu veux des photos (cérémonie, cocktail, etc.)</li>
<li>DJ ou musicien : quand ils arrivent, quelle heure ils finissent, quelle ambiance</li>
<li>Fleuriste : commande les fleurs maintenant (timing : 3 jours avant le mariage pour une fraîcheur max)</li>
</ul>

<p><strong>Achète ta robe</strong></p>
<ul>
<li>Sérieusement, 6 mois c'est le bon timing</li>
<li>Ça donne 4 mois pour les ajustements</li>
<li>Si tu l'achètes plus tard et qu'il y a un problème ? T'es stressée.</li>
</ul>

<p><strong>Crée ta liste de mariage (si tu veux une)</strong></p>
<ul>
<li>Choisis le type (Zankyou, liste papier, Amazon, peu importe)</li>
<li>Mets des choses de prix variés (20€ à 500€)</li>
<li>Partage-la avec les gens</li>
<li>C'est optionnel, mais si tu le fais, fais-le maintenant</li>
