<h2>1. À 18 mois avant : Rêver et décider</h2>

<p>C'est la phase "qu'est-ce qu'on fait vraiment". Peu de gens vont te dire, mais c'est ici que la plupart des regrets se décident.</p>

<h3>Essentiels (fais-les vraiment)</h3>

<p><strong>Discutez la vision ensemble</strong></p>
