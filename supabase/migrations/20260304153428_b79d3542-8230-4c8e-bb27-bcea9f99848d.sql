<li>Vérifie que tes témoins/demoiselles d'honneur savent ce qu'ils font</li>
<li>Contacte les invités qui vont loin pour confirmer qu'ils viennent bien</li>
<li>Prépare un petit toiletries bag pour le jour J (tampons, band-aids, hair pins, pinceau à lèvres, tout ça)</li>
</ul>

<h3>Ce que tu dois ABSOLUMENT ignorer à 3 mois</h3>
<ul>
<li>Stresser sur la météo (elle change 15 fois avant le jour J)</li>
<li>Refondre ta décoration</li>
<li>Changer le menu sans raison</li>
<li>Peaufiner les détails de table (placement exact des couverts, etc.)</li>
</ul>

<h2>5. À 1 mois avant : Respirer</h2>

<p>À ce point, tout est fait. Sérieusement. Tu peux relax.</p>

<h3>Essentiels (vraiment fais-les)</h3>

<p><strong>Confirmations finales</strong></p>
<ul>
<li>Call à chaque prestataire : "Vous êtes bien là samedi 15 septembre 10h ?"</li>
<li>Réconfirme le nombre d'invités final avec le traiteur</li>
<li>Confirme avec le photographe que tout est clair</li>
</ul>

<p><strong>Détails ultimes</strong></p>
<ul>
<li>T'as ta robe et elle est à la bonne taille ?</li>
<li>Costume du marié — ajustements finis ?</li>
<li>Tes chaussures — tu peux marcher dedans pendant 12h ?</li>
<li>Tes bijoux, ton voile, ton bouquet de mariée — tout commandé ?</li>
</ul>

<p><strong>Dernières invitations</strong></p>
<p>T'as oublié quelqu'un ? C'est le moment d'appeler en direct si c'est urgent.</p>

<p><strong>Informations pratiques finales</strong></p>
<ul>
<li>T'as reconfirmé les parking arrangements ?</li>
<li>Les gens qui viennent de loin, tu as repéré les hôtels proches ?</li>
<li>T'as un plan de crise si on doit se déplacer dedans (hôtel backup près du lieu, si c'est dehors et qu'il pleut) ?</li>
</ul>

<h3>Ce que tu dois ABSOLUMENT ignorer à 1 mois</h3>
<ul>
<li>Changer quoi que ce soit de significatif</li>
<li>Stresser sur les petits détails</li>
<li>Accueillir de nouveaux invités</li>
<li>Refaçonner le menu</li>
</ul>

<h2>6. À 1 semaine avant : Vérifier et respirer</h2>

<h3>Essentiels (vraiment fais-les)</h3>

<p><strong>Confirmations définitives</strong></p>
<ul>
<li>Email/SMS à chaque prestataire : "demain 10h, vous êtes là ?"</li>
<li>Numéro de mobile du lieu, traiteur, photographe, DJ — tu l'as ?</li>
<li>Plan B si quelque chose foire : qui tu appelles ?</li>
</ul>

<p><strong>Vérifications pratiques</strong></p>
<ul>
<li>T'as testé ta robe pour te sentir bien ?</li>
<li>Maquillage/coiffure — tu l'as testé avant le jour J ?</li>
<li>Chaussures — tu peux vraiment marcher dedans ?</li>
<li>Bijoux, accessoires — tout ok ?</li>
</ul>

<p><strong>Et voilà c'est fini</strong></p>
<p>Une semaine avant le mariage, tu dois avoir ZÉRO choses à faire sauf te préparer psychologiquement.</p>

<h2>7. Le jour J : Avoir un rôle assigné</h2>

<p>Tu dois pas gérer ton mariage le jour J. C'est pas possible et c'est pas normal.</p>

<h3>Assigne les rôles avant</h3>
<ul>
<li><strong>Quelqu'un pour la logistique</strong> : ta mère, ta meilleure amie, quelqu'un d'organisé. Cette personne checke que le traiteur sert à l'heure, que les fleurs sont en place, que les tables sont bien setup. Elle est le contact du lieu et des prestataires.</li>
<li><strong>Quelqu'un pour les invités</strong> : accueille les gens, montre où sont les toilettes, où s'asseoir au cocktail, tout ça.</li>
<li><strong>Toi</strong> : tu assistes à ton mariage. Tu prends des photos, tu parles avec les gens, tu profites.</li>
</ul>

<p>Les prestataires savent ce qu'ils font. Le lieu sait comment faire. Tu dois relax.</p>

