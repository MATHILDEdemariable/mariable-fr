<p><strong>Discute de la cérémonie formellement</strong></p>
<ul>
<li>Mairie ou lieu privé ?</li>
<li>Qui dit les vœux ? Dans quel ordre ?</li>
<li>Qui lit le texte pendant la cérémonie ?</li>
<li>Timing exact (20 min ? 45 min ?)</li>
<li>Avec qui tu veux rentrer en premier (père ? Les deux parents ? Seule ?)</li>
</ul>
