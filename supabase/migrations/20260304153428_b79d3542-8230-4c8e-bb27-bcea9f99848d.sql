<li>Envoyer des save-the-date si tu as déjà envoyé les faire-parts</li>
</ul>

<h2>4. À 3 mois avant : Les finitions</h2>

<p>À ce point, 95% du travail est fait. C'est du réglage.</p>

<h3>Essentiels (vraiment fais-les)</h3>

<p><strong>Recompte les invités confirmés</strong></p>
<ul>
<li>Regarde qui a répondu, qui a dit oui</li>
<li>Envoie une relance à ceux qui ont pas répondu</li>
<li>Donne le nombre exact au traiteur (FINAL)</li>
<li>Donne le nombre exact au lieu aussi</li>
</ul>

<p><strong>Finalise les menus</strong></p>
<ul>
<li>Combien de choix ? (une entrée, deux plats, etc. ?)</li>
<li>Nota : les invités peuvent changer d'avis avant, accepte ça</li>
<li>Imprime le menu ou c'est le traiteur qui le fait</li>
<li>Test le menu final avec le traiteur (dégustation 2)</li>
</ul>

<p><strong>Confirme avec le photographe</strong></p>
<ul>
<li>Shot list : qu'est-ce que tu veux absolument (échange des alliances, premier baiser, father-daughter dance)</li>
<li>Timing exact du jour J</li>
<li>Où il doit arriver, stationner, tout ça</li>
<li>Les coordonnées mobiles pour le jour J</li>
</ul>

<p><strong>Finalise la playlist (ou donne-la au DJ)</strong></p>
<ul>
<li>Si c'est une playlist Spotify, crée-la et partage-la</li>
<li>Si c'est un DJ, donne-lui tes préférences (genres, morceaux à absolument éviter, style de la soirée)</li>
</ul>

<p><strong>Crée le timing exact du jour J</strong></p>
<ul>
<li>10h00 : invités arrivent</li>
<li>10h15 : cérémonie commence</li>
<li>10h45 : cérémonie finie</li>
<li>11h : cocktail</li>
<li>13h : entrée</li>
</ul>
<p>Donne ça au lieu, au traiteur, au photographe, au DJ, à ta mère, à tout le monde. Tout le monde doit savoir.</p>

<p><strong>Finalise la décoration</strong></p>
<ul>
<li>Commande les fleurs (3 jours avant)</li>
<li>Si tu as un décorateur, finale check que vous êtes alignés</li>
<li>Commande les bougies, guirlandes, tout ce qu'il te faut</li>
</ul>

<p><strong>Prépare les extras</strong></p>
<ul>
<li>Livret de cérémonie si tu en veux (à imprimer toi-même ou commandé)</li>
<li>Numéros de table</li>
<li>Menus à imprimer</li>
<li>Remerciements (même basiques, pas trop fancy)</li>
</ul>

<p><strong>Vérifie les assurances et légalités</strong></p>
<ul>
<li>Le lieu a une assurance ? (coverage si quelque chose arrive)</li>
<li>T'as besoin de permis ? (si tu as musique dehors, parfois oui)</li>
<li>Déclaration à la mairie de la célébration ?</li>
</ul>

<h3>Choses utiles</h3>
<ul>
