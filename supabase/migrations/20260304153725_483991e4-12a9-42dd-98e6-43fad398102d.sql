<h2>Le cadre de décision : comment vraiment choisir</h2>

<h3>Étape 1 : Définis ton "intérieur"</h3>

<p>L'intérieur, c'est les gens non-négociables. Les gens pour qui tu ferais détour à 23h. Pour la plupart des gens, cet "intérieur" c'est :</p>
<ul>
<li>Le/la partenaire (bien sûr)</li>
<li>Les parents (mais ne pas en inviter un parce qu'il y a tension ? C'est légitime aussi)</li>
<li>Les frères/sœurs</li>
<li>Les meilleur(e)s ami(e)s</li>
<li>Les gens avec qui tu as vraiment une relation</li>
</ul>
<p>C'est généralement entre 10 et 30 personnes.</p>

<h3>Étape 2 : Accepte qu'il y ait une "couronne"</h3>

<p>En dehors de l'intérieur, il y a une couronne : les gens qui comptent, mais pas au même niveau. C'est ok d'inviter ces gens. C'est aussi ok de ne pas les inviter.</p>

<h3>Étape 3 : Détermine ton "non-négociable" financier</h3>

<p>Décide du nombre de personnes que tu veux vraiment pour ton mariage. Si tu dis 30 et qu'une cousine lointaine te met dans la culpabilité, ça te coûte quoi ? Au minimum 200€ de repas + du stress logistique.</p>

<h3>Étape 4 : Fais ta liste et regarde-la</h3>

<p>Écris la liste complète. Regarde-la et pose-toi une question honnête : "Si je regarde chaque nom, est-ce que je serais vraiment heureux(se) de les voir là ?"</p>

<p>Si la réponse est non, retire-les.</p>

<h2>Les cas spéciaux (et comment les gérer)</h2>

<h3>"Mes parents ne veulent pas venir si ce n'est pas grande famille"</h3>
<p>Ok. C'est leur choix. Tu fais ton mariage avec ou sans eux. Ce qui arrive rarement ? Que le parent ne vienne vraiment pas. La plupart du temps, c'était un ultimatum vide.</p>

<h3>"Il y a une tension avec un membre de la famille"</h3>
<p>Tu ne dois pas inviter quelqu'un avec qui tu as une relation tendue juste pour "que ce soit ok en famille". Le jour de ton mariage, tu dois te sentir safe et heureux.</p>

<h3>"Les enfants : je les invite ou pas ?"</h3>
<p>Deux approches :</p>
<ul>
<li>Tu invites tous les enfants de la famille (cohérent, mais plus lourd)</li>
<li>Tu invites les enfants des gens les plus proches (plus sélectif)</li>
</ul>
<p>Il n'y a pas de bonne réponse. Il y a juste la réponse qui te convient.</p>

<h3>"La famille est séparée/recomposée"</h3>
<p>Définis qui tu considères comme ta "famille". Pas par le sang, mais par la connexion réelle.</p>

<h2>Ce que tu dois absolument ne PAS faire</h2>

<ul>
<li><strong>Ne pas inviter quelqu'un par culpabilité</strong> — cette personne sentira que tu n'es pas vraiment enthousiasmé(e)</li>
